import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { chromium } from 'playwright'

test('core news works inside the original system on desktop and mobile', async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    await page.addInitScript(() => { window.__geoIdentity = { userId: 'test', role: 'project_admin', projectId: 'test-project' } })
    const actions = []
    const site = await browser.newPage({ viewport: { width: 1280, height: 800 } })
    await site.setContent('<h1>本地新闻平台</h1><label>标题 <input></label><p>文章发布 / 发稿列表</p>')
    const jpeg = (await site.screenshot({ type: 'jpeg' })).toString('base64'); await site.close()
    await page.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.pathname.startsWith('/api/core-news-browser/')) {
        const action = url.pathname.split('/').at(-1); actions.push({ action, data: route.request().postDataJSON() })
        if (action === 'batches') return route.fulfill({json:{ok:true,identity:'test',brand:'测试品牌',batches:Array.from({length:21},(_,i)=>({id:'task'+(i+1),name:'本地任务'+(i+1),planned:11,completed:11}))}})
        if (action === 'selection') return route.fulfill({ json: { ok: true, identity: 'test', brand: '测试品牌', batches:[{id:'task1',available:11},{id:'task21',available:11}], articles: Array.from({ length: 21 }, (_, i) => ({ id: String(i), title: '本地文章' + i })) } })
        if(action==='media')return route.fulfill({json:{ok:true,media:[{id:'m1',name:'本地媒体',priceFen:200,category:'新闻'}]}})
        if(action==='plan')return route.fulfill({json:{ok:true,articleCount:2,unassignedCount:19,totalFen:400,assignments:[{title:'本地文章0',mediaName:'本地媒体',reason:'按批次顺序分配'}],canSubmit:false,submissionBlocker:'未提交订单'}})
        return route.fulfill({ json: { ok: true, image: jpeg, url: 'http://xinwen.7chacha.com/user/order/index.html' } })
      }
      if (url.pathname.startsWith('/api/')) return route.fulfill({ json: { ok: true, value: null } })
      const asset = url.pathname.match(/^\/gongju\/assets\/([\w.-]+\.(js|css))$/)
      if (asset) return route.fulfill({ contentType: asset[2] === 'js' ? 'application/javascript' : 'text/css', body: await fs.readFile('dist/assets/' + asset[1]) })
      if (url.pathname.endsWith('/core-news-browser.js')) return route.fulfill({ contentType: 'application/javascript', body: await fs.readFile('public/core-news-browser.js') })
      return route.fulfill({ contentType: 'text/html', body: await fs.readFile('dist/index.html') })
    })
    await page.goto('http://127.0.0.1/gongju/agents#/project/core-news')
    await page.getByRole('button', { name: '打开新闻源平台', exact: true }).click()
    await page.locator('.cn-stage img[src]').waitFor()
    await page.locator('.cn-stage img').click({position:{x:80,y:80}})
    await page.locator('.cn-keyboard').fill('输入验证')
    await page.getByRole('tab',{name:'发布工作台',exact:true}).click()
    await page.getByRole('button', { name: '读取任务批次', exact: true }).click()
    await page.getByRole('checkbox',{name:'选择批次：本地任务1',exact:true}).waitFor()
    assert.equal(await page.locator('.cn-batch-table input').count(),20)
    await page.getByRole('checkbox',{name:'选择批次：本地任务1',exact:true}).check()
    await page.getByRole('button',{name:'下一页批次',exact:true}).click()
    await page.getByRole('checkbox',{name:'选择批次：本地任务21',exact:true}).check()
    await page.getByRole('button',{name:'上一页批次',exact:true}).click()
    assert.equal(await page.getByRole('checkbox',{name:'选择批次：本地任务1',exact:true}).isChecked(),true)
    await page.getByRole('button',{name:'读取所选批次文章',exact:true}).click()
    await page.getByText('已选2个批次 · 记录已生成22篇 · 实际可用21篇（已去重）',{exact:true}).waitFor()
    assert.deepEqual(actions.find(x=>x.action==='selection').data.batchIds,['task1','task21'])
    await page.getByText('单篇填稿',{exact:true}).click()
    await page.getByRole('option', { name: '本地文章0', exact: true }).waitFor({ state: 'attached' })
    assert.equal(await page.getByRole('combobox',{name:'选择当前品牌文章',exact:true}).locator('option').count(), 21)
    await page.getByRole('button', { name: '下一页', exact: true }).click()
    assert.equal(await page.getByRole('combobox',{name:'选择当前品牌文章',exact:true}).locator('option').count(), 2)
    await page.getByRole('combobox', { name: '选择当前品牌文章' }).selectOption('20')
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: '填入文章', exact: true }).click()
    await page.getByText('稿件已填入，未提交订单。请核对媒体、图片和费用。', { exact: true }).waitFor()
    assert.equal(actions.find(x => x.action === 'fill').data.id, '20')
    assert.deepEqual(actions.find(x => x.action === 'fill').data.batchIds, ['task1','task21'])
    await page.getByRole('tab',{name:'发布工作台',exact:true}).click()
    await page.getByRole('button',{name:'读取平台已选媒体',exact:true}).click()
    await page.getByLabel('本地媒体发布篇数',{exact:true}).fill('2')
    await page.getByRole('button',{name:'生成匹配清单',exact:true}).click()
    await page.getByText('已分配2篇，未分配19篇；预计费用¥4.00',{exact:true}).waitFor()
    assert.deepEqual(actions.find(x=>x.action==='plan').data.targets,[{id:'m1',count:2}])
    assert.deepEqual(actions.find(x=>x.action==='plan').data.batchIds,['task1','task21'])
    await page.screenshot({path:'outputs/core-news-workbench-desktop.png',fullPage:true})
    await page.setViewportSize({width:390,height:844})
    assert.equal(await page.locator('.core-news-source').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true)
    await page.screenshot({path:'outputs/core-news-workbench-mobile.png',fullPage:true})
    await page.setViewportSize({width:1440,height:1000})
    await page.getByRole('tab',{name:'新闻平台',exact:true}).click()
    await page.getByRole('button',{name:'平台登录',exact:true}).click()
    await page.getByRole('button',{name:'发稿列表',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.cn-address').textContent.includes('/user/order/'))
    assert.ok(actions.some(x=>x.action==='login'))
    assert.ok(actions.some(x=>x.action==='orders'))
    assert.ok(actions.some(x=>x.action==='input'&&x.data.type==='click'))
    assert.ok(actions.some(x=>x.action==='input'&&x.data.text==='输入验证'))
    assert.equal(await page.locator('iframe').count(), 0)
    await page.screenshot({ path: 'outputs/core-news-integrated-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.locator('.core-news-source').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true)
    await page.screenshot({ path: 'outputs/core-news-integrated-mobile.png', fullPage: true })
    await page.evaluate(() => { location.hash = '#/project/tasks' })
    await page.locator('.core-news-source').waitFor({ state: 'detached' })
    assert.equal(await page.locator('.cn-stage').count(), 0)
  } finally { await browser.close() }
})
