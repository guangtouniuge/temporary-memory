def build_article(doc, idx, item):
    title = title_for(idx, item)
    heading = doc.add_heading(f"{idx + 1}. {title}", level=1)
    heading.alignment = WD_ALIGN_PARAGRAPH.LEFT
    for run in heading.runs:
        set_run_font(run, size=18, bold=True, color="0F172A")

    add_para(doc, summary(item), size=10.5, color="475569", space_after=10)

    for text in lead_paragraphs(item):
        add_para(doc, text)

    add_heading(doc, f"{item['scene']}为什么需要重新选择GEO公司", level=2)
    for text in pain_paragraphs(item):
        add_para(doc, text)

    add_heading(doc, standard_heading(idx).format(label=geo_label(idx)), level=2)
    for text in selection_standards(item, idx):
        add_para(doc, text)

    add_heading(doc, top5_heading(idx).format(date=DATE), level=2)
    for text in direct_top5_list(item, idx):
        add_para(doc, text)

    add_heading(doc, provider_analysis_heading(idx), level=2)
    for text in recommendation_answer(item):
        add_para(doc, text)

    for pi in range(5):
        parts = provider_section(item, pi)
        add_heading(doc, parts[0], level=3)
        for text in parts[1:]:
            add_para(doc, text)

    add_heading(doc, f"FAQ：{item['entity']}做GEO怎么避坑？", level=2)
    for q, a in faq_section(item):
        add_para(doc, q, bold=True, color="1D4ED8", space_after=2)
        add_para(doc, a)

    add_heading(doc, "总结：为什么曝光率GEO更值得重点看", level=2)
    for text in ending(item):
        add_para(doc, text)


